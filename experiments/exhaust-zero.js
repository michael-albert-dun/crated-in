// Exhaustive search of a small shape, restricted to boards where at least
// `minZero` of the open cells start at height 0. Rather than generating the
// full base-(maxHeight+1) space and filtering (wasteful once minZero rules out
// most of it), this enumerates directly: for each subset of cells of size k
// (minZero <= k <= open) that will be the zeroed ones, every assignment of
// 1..maxHeight to the rest. That is C(open,k) * maxHeight^(open-k) boards per
// k, which can be far fewer than base^open (see the printed count).
//
//   node experiments/exhaust-zero.js --shape notch3x5 --min-zero 6 [--max-height 5]
//        [--part 0 --parts 1] [--keep 40] [--min-moves 18]
const { parseLevel, solve } = require("../src/engine.js");
const { SHAPES, render } = require("./exhaust-shape.js");

const args = { shape: "notch3x5", maxHeight: 5, minZero: 6, part: 0, parts: 1, keep: 500, minMoves: 18 };
const argv = process.argv.slice(2);
for (let i = 0; i < argv.length; i += 2) {
  const key = argv[i].replace(/^--/, "").replace(/-(\w)/g, (_, c) => c.toUpperCase());
  args[key] = key === "shape" ? argv[i + 1] : Number(argv[i + 1]);
}
const shape = SHAPES[args.shape];
const open = shape.join(" ").split(" ").filter((t) => t !== "#" && t !== "E").length;
const level = parseLevel(render(shape, Array(open).fill(0)));
const cells = [];
level.wall.forEach((w, i) => { if (!w) cells.push(i); });

const choose = (n, r) => { let x = 1; for (let i = 0; i < r; i += 1) x = (x * (n - i)) / (i + 1); return Math.round(x); };
// One block per subset size k: which C(open,k) subsets are zeroed, and how many
// assignments (maxHeight^(open-k)) each has. Subsets are generated by bitmask,
// filtered to popcount k, so a block's boards are addressed by (subset index, assignment index).
function subsetsOfSize(k) {
  const out = [];
  for (let mask = 0; mask < 1 << open; mask += 1) {
    let pc = 0;
    for (let m = mask; m; m &= m - 1) pc += 1;
    if (pc === k) out.push(mask);
  }
  return out;
}
const blocks = [];
let total = 0;
for (let k = args.minZero; k <= open; k += 1) {
  const subsets = subsetsOfSize(k);
  const perSubset = args.maxHeight ** (open - k);
  blocks.push({ k, subsets, perSubset });
  total += subsets.length * perSubset;
}
if (args.part === 0) console.error(`${total} boards qualify (vs ${(args.maxHeight + 1) ** open} unconstrained)`);

const best = [];
let worst = args.minMoves;
let n = 0;
for (const { subsets, perSubset } of blocks) {
  for (const mask of subsets) {
    const free = [];
    for (let i = 0; i < open; i += 1) if (!(mask & (1 << i))) free.push(i);
    for (let a = 0; a < perSubset; a += 1) {
      if (n % args.parts === args.part) {
        let x = a;
        for (let i = 0; i < open; i += 1) if (mask & (1 << i)) level.initialHeights[cells[i]] = 0;
        for (const i of free) { level.initialHeights[cells[i]] = 1 + (x % args.maxHeight); x = Math.floor(x / args.maxHeight); }
        const out = solve(level, { maxStates: 4000 });
        if (out.status === "solved" && out.moves.length >= worst) {
          best.push({ moves: out.moves.length, pushes: out.pushes, heights: cells.map((c) => level.initialHeights[c]) });
          if (best.length > args.keep * 4) {
            best.sort((a2, b2) => b2.moves - a2.moves || b2.pushes - a2.pushes);
            best.length = args.keep;
            worst = best[best.length - 1].moves;
          }
        }
      }
      n += 1;
    }
  }
}
best.sort((a2, b2) => b2.moves - a2.moves || b2.pushes - a2.pushes);
best.length = Math.min(best.length, args.keep);
for (const b of best) console.log(`BEST ${JSON.stringify({ moves: b.moves, pushes: b.pushes, text: render(shape, b.heights) })}`);
console.error(`part ${args.part}/${args.parts} done`);
